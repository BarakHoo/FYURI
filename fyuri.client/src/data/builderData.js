export const getDefaultSelections = () =>
  Object.fromEntries(builderCategories.map((c) => [c.id, null]));

// Options valid for a given device type (options without a deviceTypes
// restriction fit all form factors)
export const getOptionsForDevice = (category, deviceTypeId) =>
  category.options.filter(
    (o) => !o.deviceTypes || o.deviceTypes.includes(deviceTypeId)
  );

export const getTubeCount = (deviceTypeId) =>
  deviceTypes.find((d) => d.id === deviceTypeId)?.tubes ?? 1;
